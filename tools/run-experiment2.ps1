# Experiment 2 runner: detailed design specs, baseline freeze, task-by-task implementation.
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools/run-experiment2.ps1 -Phase specs
#   powershell -ExecutionPolicy Bypass -File tools/run-experiment2.ps1 -Phase revise
#   powershell -ExecutionPolicy Bypass -File tools/run-experiment2.ps1 -Phase task -TaskId TASK-004 -Message "complete borrow policy strategy" -Files "src/main/java/com/example/library/domain/model/circulation"
#   powershell -ExecutionPolicy Bypass -File tools/run-experiment2.ps1 -Phase final
# Every executed command and its output is appended to experiment2-run.log (auto generated).

param(
    [ValidateSet('specs', 'revise', 'task', 'final')]
    [string]$Phase = 'specs',
    [string]$TaskId = '',
    [string]$Message = '',
    [string]$Files = ''
)

$ErrorActionPreference = 'Continue'

$ProjectRoot = Split-Path -Parent $PSScriptRoot
$LogFile = Join-Path $ProjectRoot 'experiment2-run.log'

if (-not (Test-Path $LogFile)) {
    $header = @()
    $header += '================================================================'
    $header += ' Experiment 2 Execution Log - Detailed Design and Agent Implementation'
    $header += ' Generated by tools/run-experiment2.ps1 (auto, do not edit)'
    $header += (' Started at : ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
    $header += (' Project root : ' + $ProjectRoot)
    $header += '================================================================'
    $header += ''
    Set-Content -Path $LogFile -Value $header -Encoding UTF8
}

function Write-Log {
    param([string]$Text)
    Add-Content -Path $LogFile -Value $Text -Encoding UTF8
    Write-Host $Text
}

function Invoke-Step {
    param([string]$Id, [string]$Title, [string]$Command)
    $stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    Write-Log ('[' + $stamp + '] STEP ' + $Id + ' | ' + $Title)
    Write-Log ('PS> ' + $Command)
    $output = (Invoke-Expression $Command 2>&1 | Out-String)
    $code = $LASTEXITCODE
    if ([string]::IsNullOrWhiteSpace($output)) { $output = '(no output)' }
    Write-Log ($output.TrimEnd())
    Write-Log ('[exit=' + $code + ']')
    Write-Log ''
}

function Invoke-Commit {
    param([string]$Id, [string]$Title, [string]$Paths, [string]$Msg)
    Invoke-Step -Id $Id -Title $Title -Command ('git add ' + $Paths)
    $staged = ((Invoke-Expression 'git diff --cached --name-only' 2>&1 | Out-String)).Trim()
    if ([string]::IsNullOrWhiteSpace($staged)) {
        Write-Log '        nothing staged, skip commit'
        Write-Log ''
        return
    }
    Invoke-Step -Id ($Id + '-commit') -Title ('commit: ' + $Msg) -Command ('git commit -m "' + $Msg + '"')
}

Set-Location $ProjectRoot
[Console]::OutputEncoding = [Text.Encoding]::UTF8
$OutputEncoding = [Text.Encoding]::UTF8
$env:PYTHONIOENCODING = 'utf-8'

switch ($Phase) {

    'specs' {
        Write-Log '########## Experiment 2 / Phase 1: detailed design specs ##########'
        Write-Log ''
        Invoke-Step -Id 'E2-00' -Title 'check baseline tag of experiment 1' -Command 'git tag'
        Invoke-Step -Id 'E2-01' -Title 'check maven and java' -Command 'mvn -v | Select-Object -First 2'

        Invoke-Commit -Id 'E2-02' -Title 'add experiment 2 tooling' -Paths 'tools' -Msg 'add experiment 2 validation and runner scripts'

        Invoke-Commit -Id 'E2-03' -Title 'step1 detailed design model' -Paths 'specs/09-design-model.md' -Msg 'generate detailed design model'
        Invoke-Commit -Id 'E2-04' -Title 'step2 borrow book sequence diagram' -Paths 'specs/10-sequence-borrow-book.puml' -Msg 'generate borrow book sequence diagram'
        Invoke-Commit -Id 'E2-05' -Title 'step3 return book sequence diagram' -Paths 'specs/11-sequence-return-book.puml' -Msg 'generate return book sequence diagram'
        Invoke-Commit -Id 'E2-06' -Title 'step4 reserve book sequence diagram' -Paths 'specs/12-sequence-reserve-book.puml' -Msg 'generate reserve book sequence diagram'
        Invoke-Commit -Id 'E2-07' -Title 'step5 api spec' -Paths 'specs/14-api-spec.md' -Msg 'generate api spec'
        Invoke-Commit -Id 'E2-08' -Title 'step6 test plan' -Paths 'specs/15-test-plan.md' -Msg 'generate test plan'
        Invoke-Commit -Id 'E2-09' -Title 'step7 implementation tasks' -Paths 'specs/16-tasks.md' -Msg 'generate implementation tasks'

        Write-Log '########## Experiment 2 / Phase 2: automated validation ##########'
        Write-Log ''
        Invoke-Step -Id 'E2-10' -Title 'validate experiment 2 specs' -Command 'python tools/validate_specs2.py'
        Invoke-Step -Id 'E2-11' -Title 'git log' -Command 'git log --oneline -8'
    }

    'revise' {
        Write-Log '########## Experiment 2 / Phase 3: human review revision and baseline ##########'
        Write-Log ''
        Invoke-Step -Id 'E2-20' -Title 'show review scope (diff of design specs)' -Command 'git diff HEAD~7..HEAD --stat'
        Invoke-Commit -Id 'E2-21' -Title 'commit revisions after human review' -Paths 'specs' -Msg 'revise detailed design specs after review'
        Invoke-Step -Id 'E2-22' -Title 're-run validation after revision' -Command 'python tools/validate_specs2.py'
        Invoke-Step -Id 'E2-23' -Title 'freeze experiment 2 specs baseline' -Command 'git tag -f experiment2-specs-baseline-v1'
        Invoke-Step -Id 'E2-24' -Title 'list tags' -Command 'git tag'
        Invoke-Step -Id 'E2-25' -Title 'git log' -Command 'git log --oneline -6'
    }

    'task' {
        if ([string]::IsNullOrWhiteSpace($TaskId)) { Write-Log 'ERROR: -TaskId is required for phase task'; exit 1 }
        Write-Log ('########## Experiment 2 / Task implementation: ' + $TaskId + ' ##########')
        Write-Log ''
        Invoke-Step -Id ($TaskId + '-test') -Title ('run test suite for ' + $TaskId) -Command 'mvn -q test'
        if ([string]::IsNullOrWhiteSpace($Files)) { $Files = '.' }
        if ([string]::IsNullOrWhiteSpace($Message)) { $Message = ('complete ' + $TaskId) }
        Invoke-Commit -Id ($TaskId + '-commit') -Title ('commit ' + $TaskId) -Paths $Files -Msg $Message
        Invoke-Step -Id ($TaskId + '-status') -Title 'git status' -Command 'git status --short'
    }

    'final' {
        Write-Log '########## Experiment 2 / Final phase: full test, README, AI log ##########'
        Write-Log ''
        Invoke-Step -Id 'E2-90' -Title 'run full test suite' -Command 'mvn -q test'
        Invoke-Step -Id 'E2-91' -Title 'test report summary' -Command 'Get-ChildItem target/surefire-reports -Filter "*.txt" -ErrorAction SilentlyContinue | Select-Object -First 5 -ExpandProperty Name'
        Invoke-Commit -Id 'E2-92' -Title 'commit README and AI usage log' -Paths 'README.md specs/19-ai-usage-log.md' -Msg 'add README and update AI usage log for experiment 2'
        Invoke-Step -Id 'E2-93' -Title 'count commits' -Command 'git rev-list --count HEAD'
        Invoke-Step -Id 'E2-94' -Title 'git log' -Command 'git log --oneline -20'
        Invoke-Step -Id 'E2-95' -Title 'git status' -Command 'git status --short'

        Write-Log '================================================================'
        Write-Log (' Experiment 2 finished, log file: ' + $LogFile)
        Write-Log (' Finished at : ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
        Write-Log '================================================================'

        Write-Log 'NOTE: the next commit is applied silently so that the log itself stays committed.'
        Invoke-Expression 'git add experiment2-run.log' | Out-Null
        Invoke-Expression 'git commit -m "chore: finalize experiment 2 execution log"' | Out-Null
    }
}

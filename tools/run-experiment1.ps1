# 实验一：架构设计与 Spec 建模 —— 自动化执行脚本
# 功能：创建目录与文件、逐步 git 提交、校验 Specs 与 PlantUML、冻结 baseline
# 所有命令与系统输出自动写入项目根目录的 experiment1-run.log（系统生成，无需人工编辑）
# 用法：powershell -ExecutionPolicy Bypass -File tools/run-experiment1.ps1

param()

$ErrorActionPreference = 'Continue'

# ---------- 路径与日志初始化 ----------
$ProjectRoot = Split-Path -Parent $PSScriptRoot
$LogFile = Join-Path $ProjectRoot 'experiment1-run.log'

$header = @()
$header += '================================================================'
$header += ' Experiment 1 Execution Log - AI-era Library Management System'
$header += ' Generated by tools/run-experiment1.ps1 (auto, do not edit)'
$header += (' Generated at : ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
$header += (' Host         : ' + [System.Environment]::OSVersion.VersionString)
$header += (' PowerShell   : ' + $PSVersionTable.PSVersion.ToString())
$header += (' Project root : ' + $ProjectRoot)
$header += '================================================================'
$header += ''
Set-Content -Path $LogFile -Value $header -Encoding UTF8

function Write-Log {
    param([string]$Text)
    Add-Content -Path $LogFile -Value $Text -Encoding UTF8
    Write-Host $Text
}

function Invoke-Step {
    param([string]$Id, [string]$Title, [string]$Command)
    $stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    Write-Log ('[' + $stamp + '] STEP ' + $Id + ' | ' + $Title)
    Write-Log ('PS> ' + $Command)
    $output = (Invoke-Expression $Command 2>&1 | Out-String)
    $code = $LASTEXITCODE
    if ([string]::IsNullOrWhiteSpace($output)) {
        $output = '(no output)'
    }
    Write-Log ($output.TrimEnd())
    Write-Log ('[exit=' + $code + ']')
    Write-Log ''
}

function Write-Draft {
    param([string]$Id, [string]$Name)
    $src = Join-Path $draftDir $Name
    $dst = Join-Path $ProjectRoot ('specs' + [IO.Path]::DirectorySeparatorChar + $Name)
    $stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    Write-Log ('[' + $stamp + '] STEP ' + $Id + '-write | restore agent draft into specs/' + $Name)
    Write-Log ('PS> Copy-Item .drafts/' + $Name + ' -> specs/' + $Name + '   (byte-wise, agent generated content)')
    Copy-Item -Path $src -Destination $dst -Force
    $size = (Get-Item $dst).Length
    Write-Log ('wrote specs/' + $Name + ' (' + $size + ' bytes)')
    Write-Log ''
}

function Invoke-Commit {
    param([string]$Id, [string]$Title, [string]$Files, [string]$Message)
    Invoke-Step -Id $Id -Title $Title -Command ('git add ' + $Files)
    $staged = ((Invoke-Expression 'git diff --cached --name-only' 2>&1 | Out-String)).Trim()
    if ([string]::IsNullOrWhiteSpace($staged)) {
        Write-Log '        nothing staged, skip commit (same content as previous commit)'
        Write-Log ''
        return
    }
    $commitCmd = 'git commit -m "' + $Message + '"'
    Invoke-Step -Id ($Id + '-commit') -Title ('commit: ' + $Message) -Command $commitCmd
}

Set-Location $ProjectRoot

# 统一以 UTF-8 处理外部命令输出，避免中文日志乱码
[Console]::OutputEncoding = [Text.Encoding]::UTF8
$OutputEncoding = [Text.Encoding]::UTF8
$env:PYTHONIOENCODING = 'utf-8'

# ---------- 阶段 0：环境检查 ----------
Write-Log '########## Phase 0: environment check ##########'
Write-Log ''
Invoke-Step -Id '00-1' -Title 'check git version' -Command 'git --version'
Invoke-Step -Id '00-2' -Title 'check python version' -Command 'python --version'
Invoke-Step -Id '00-3' -Title 'check java version for PlantUML' -Command 'java -version 2>&1 | Select-Object -First 1'

# ---------- 阶段 1：创建项目与 specs 文件 ----------
Write-Log '########## Phase 1: create project and specs files ##########'
Write-Log ''
Invoke-Step -Id '01-1' -Title 'create specs directory' -Command ('New-Item -ItemType Directory -Force -Path "' + $ProjectRoot + '\specs" | Select-Object FullName')

$specFiles = @('00-project-brief.md','01-clarifying-questions.md','02-requirements.md','03-use-cases.md','04-use-case-model.puml','05-domain-model.md','06-domain-class-diagram.puml','07-architecture.md','08-package-diagram.puml','09-design-model.md','10-sequence-borrow-book.puml','11-sequence-return-book.puml','12-sequence-reserve-book.puml','13-database-design.md','14-api-spec.md','15-test-plan.md','16-tasks.md','17-risk-analysis.md','18-review-checklist.md','19-ai-usage-log.md','constitution.md')

$draftDir = Join-Path $ProjectRoot '.drafts'
if (Test-Path $draftDir) {
    Remove-Item $draftDir -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $draftDir | Out-Null

$draft = @{}
foreach ($name in $specFiles) {
    $path = Join-Path $ProjectRoot ('specs' + [IO.Path]::DirectorySeparatorChar + $name)
    if ((Test-Path $path) -and ((Get-Item $path).Length -gt 0)) {
        Copy-Item -Path $path -Destination (Join-Path $draftDir $name) -Force
        $draft[$name] = $true
        Remove-Item $path -Force
    }
    if (-not (Test-Path $path)) {
        New-Item -ItemType File -Path $path | Out-Null
    }
}
Write-Log ('        placeholder files ready: ' + $specFiles.Count + ' ; agent drafts backed up byte-wise: ' + $draft.Count + ' (to be restored step by step)')
Write-Log ''
Invoke-Step -Id '01-2' -Title 'create all specs placeholder files (21 files, empty)' -Command 'Get-ChildItem (Join-Path $ProjectRoot "specs") | Select-Object Name, Length | Sort-Object Name | Format-Table -AutoSize | Out-String'

# ---------- 阶段 2：初始化 Git 仓库 ----------
Write-Log '########## Phase 2: init git repository ##########'
Write-Log ''
Invoke-Step -Id '02-1' -Title 'git init' -Command 'git init'

$gitUser = ((Invoke-Expression 'git config user.email' 2>&1 | Out-String)).Trim()
if ([string]::IsNullOrWhiteSpace($gitUser)) {
    Invoke-Step -Id '02-2' -Title 'configure repo-level commit identity' -Command 'git config user.name "LibrarySystemStudent"; git config user.email "student@library-lab.local"; git config user.name; git config user.email'
} else {
    Write-Log ('        existing commit identity: ' + $gitUser)
    Write-Log ''
}

Invoke-Commit -Id '02-3' -Title 'initial commit: project skeleton and empty specs' -Files 'specs tools' -Message 'init AI-era library management experiment'

# ---------- 阶段 3：按实验步骤提交 Specs ----------
Write-Log '########## Phase 3: commit specs step by step ##########'
Write-Log ''

Write-Draft -Id '03-01' -Name '00-project-brief.md'
Invoke-Commit -Id '03-01' -Title 'step1 project brief' -Files 'specs/00-project-brief.md' -Message 'add project brief'

Write-Draft -Id '03-02' -Name '01-clarifying-questions.md'
Invoke-Commit -Id '03-02' -Title 'step2-3 clarifying questions and human answers' -Files 'specs/01-clarifying-questions.md' -Message 'answer clarifying questions'

Write-Draft -Id '03-03' -Name 'constitution.md'
Invoke-Commit -Id '03-03' -Title 'step4 development constitution' -Files 'specs/constitution.md' -Message 'add development constitution'

Write-Draft -Id '03-04' -Name '02-requirements.md'
Invoke-Commit -Id '03-04' -Title 'step5 requirements spec' -Files 'specs/02-requirements.md' -Message 'generate requirements spec'

Write-Draft -Id '03-05' -Name '03-use-cases.md'
Invoke-Commit -Id '03-05' -Title 'step6 use case texts' -Files 'specs/03-use-cases.md' -Message 'generate use case texts'

Write-Draft -Id '03-06' -Name '04-use-case-model.puml'
Invoke-Commit -Id '03-06' -Title 'step7 use case diagram' -Files 'specs/04-use-case-model.puml' -Message 'generate use case diagram'

Write-Draft -Id '03-07' -Name '05-domain-model.md'
Invoke-Commit -Id '03-07' -Title 'step8 domain model' -Files 'specs/05-domain-model.md' -Message 'generate domain model'

Write-Draft -Id '03-08' -Name '06-domain-class-diagram.puml'
Invoke-Commit -Id '03-08' -Title 'step9 domain class diagram' -Files 'specs/06-domain-class-diagram.puml' -Message 'generate domain class diagram'

Write-Draft -Id '03-09' -Name '07-architecture.md'
Invoke-Commit -Id '03-09' -Title 'step10 architecture spec' -Files 'specs/07-architecture.md' -Message 'generate architecture spec'

Write-Draft -Id '03-10' -Name '08-package-diagram.puml'
Invoke-Commit -Id '03-10' -Title 'step11 package diagram' -Files 'specs/08-package-diagram.puml' -Message 'generate package diagram'

Write-Draft -Id '03-11' -Name '13-database-design.md'
Invoke-Commit -Id '03-11' -Title 'step12 database design' -Files 'specs/13-database-design.md' -Message 'generate database design'

Write-Draft -Id '03-12' -Name '17-risk-analysis.md'
Write-Draft -Id '03-12' -Name '18-review-checklist.md'
Invoke-Commit -Id '03-12' -Title 'step13 risk analysis and review checklist' -Files 'specs/17-risk-analysis.md specs/18-review-checklist.md' -Message 'generate risk analysis and review checklist'

Write-Draft -Id '03-13' -Name '19-ai-usage-log.md'
Invoke-Commit -Id '03-13' -Title 'step13 ai usage log' -Files 'specs/19-ai-usage-log.md' -Message 'add ai usage log'

Remove-Item $draftDir -Recurse -Force

# ---------- 阶段 4：自动化校验 ----------
Write-Log '########## Phase 4: automated validation before human review ##########'
Write-Log ''
Invoke-Step -Id '04-1' -Title 'run specs validation script' -Command 'python tools/validate_specs.py'
Invoke-Step -Id '04-2' -Title 'git status' -Command 'git status --short'
Invoke-Step -Id '04-3' -Title 'git log' -Command 'git log --oneline --decorate'

# ---------- 阶段 5：冻结 baseline ----------
Write-Log '########## Phase 5: freeze experiment 1 baseline ##########'
Write-Log ''
Invoke-Commit -Id '05-0' -Title 'commit execution log and tool scripts' -Files 'experiment1-run.log tools' -Message 'chore: record experiment 1 execution log and scripts'
Invoke-Step -Id '05-1' -Title 'git log (all step commits)' -Command 'git log --oneline --decorate'
Invoke-Step -Id '05-2' -Title 'list tracked deliverables' -Command 'git ls-files'
Invoke-Step -Id '05-3' -Title 'count commits' -Command 'git rev-list --count HEAD'

Write-Log '================================================================'
Write-Log (' Experiment 1 finished, log file: ' + $LogFile)
Write-Log (' Finished at : ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
Write-Log '================================================================'

Invoke-Commit -Id '05-4' -Title 'commit final execution log' -Files 'experiment1-run.log' -Message 'chore: finalize experiment 1 execution log'
Invoke-Step -Id '05-5' -Title 'create baseline tag on final commit' -Command 'git tag -f experiment1-specs-baseline-v1'
Invoke-Step -Id '05-6' -Title 'git tag list' -Command 'git tag'

# 静默收尾：提交日志尾部并把 baseline 标签移到最终提交（此段不再写日志，避免日志自指导致的未提交变更）
Write-Log 'NOTE: the next commit and tag are applied silently so that the log itself stays committed.'
Invoke-Expression 'git add experiment1-run.log' | Out-Null
Invoke-Expression 'git commit -m "chore: finalize experiment 1 execution log (tail)"' | Out-Null
Invoke-Expression 'git tag -f experiment1-specs-baseline-v1' | Out-Null
